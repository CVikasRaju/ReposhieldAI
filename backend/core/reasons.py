    PROTECTED_PATH = "PROTECTED_PATH"
    PROTECTED_TABLE = "PROTECTED_TABLE"
    SECRET_DETECTED = "SECRET_DETECTED"
    PII_DETECTED = "PII_DETECTED"
    PATH_ESCAPE = "PATH_ESCAPE"
    POLICY_TAMPER = "POLICY_TAMPER"
    EGRESS_DENIED = "EGRESS_DENIED"
    EXFIL_DETECTED = "EXFIL_DETECTED"
    OUTBOUND_WRITE = "OUTBOUND_WRITE"
    DESTRUCTIVE_COMMAND = "DESTRUCTIVE_COMMAND"
    DENIED_COMMAND = "DENIED_COMMAND"
    UNLISTED_COMMAND = "UNLISTED_COMMAND"
    SHELL_OPERATORS = "SHELL_OPERATORS"
    DESTRUCTIVE_SQL = "DESTRUCTIVE_SQL"
    UNSAFE_SQL = "UNSAFE_SQL"
    TASK_MISMATCH = "TASK_MISMATCH"
    SENSITIVE_LOCATION = "SENSITIVE_LOCATION"
    CONTENT_SENSITIVE = "CONTENT_SENSITIVE"
    BEHAVIOUR_ESCALATION = "BEHAVIOUR_ESCALATION"
    KILL_SWITCH = "KILL_SWITCH"
